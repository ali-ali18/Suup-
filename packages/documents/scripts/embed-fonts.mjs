// Writes src/fonts.generated.ts: the Geist faces the documents use, as base64, so the font travels
// inside the code (the VPS runs `dist`, the desktop app one esbuild bundle: a `.ttf` beside the
// code would be lost in the second). Geist is under the SIL Open Font License 1.1 (fonts/OFL.txt).
// Not a dependency (its peer, `next`, would drag in a lot): download and unpack the package once and
// pass its folder: `npm pack geist@1.9.0 && tar xzf geist-1.9.0.tgz`, then
// `node scripts/embed-fonts.mjs ./package` (from this folder).
import { copyFileSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const folder = process.argv[2];
if (folder === undefined) throw new Error("Pass the folder of the unpacked geist package.");
const geist = join(process.cwd(), folder);
const version = JSON.parse(readFileSync(join(geist, "package.json"), "utf8")).version;

const faces = {
  sansRegular: "geist-sans/Geist-Regular.ttf",
  sansBold: "geist-sans/Geist-Bold.ttf",
  sansItalic: "geist-sans/Geist-Italic.ttf",
  sansBoldItalic: "geist-sans/Geist-BoldItalic.ttf",
  monoRegular: "geist-mono/GeistMono-Regular.ttf",
};

let out = `// Generated by scripts/embed-fonts.mjs from geist@${version} (SIL Open Font License 1.1, see
// ../fonts/OFL.txt). Do not edit by hand.\n\n`;
for (const [name, file] of Object.entries(faces)) {
  const b64 = readFileSync(join(geist, "dist", "fonts", file)).toString("base64");
  out += `/** ${file} */\nexport const ${name} = "${b64}";\n\n`;
}
writeFileSync(join(here, "..", "src", "fonts.generated.ts"), out);
copyFileSync(join(geist, "LICENSE.txt"), join(here, "..", "fonts", "OFL.txt"));
console.log(`fonts.generated.ts: ${(out.length / 1024).toFixed(0)} KB (geist ${version})`);
